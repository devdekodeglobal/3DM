export function hexToRgb(hex: string): {r: number, g: number, b: number} | null {
  const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
  return result ? {
    r: parseInt(result[1], 16),
    g: parseInt(result[2], 16),
    b: parseInt(result[3], 16)
  } : null;
}

export function rgbToHex(r: number, g: number, b: number): string {
  return "#" + (1 << 24 | r << 16 | g << 8 | b).toString(16).slice(1).toUpperCase();
}

function colorDistance(r1: number, g1: number, b1: number, r2: number, g2: number, b2: number) {
  return Math.sqrt(Math.pow(r1 - r2, 2) + Math.pow(g1 - g2, 2) + Math.pow(b1 - b2, 2));
}

export function findClosestRAL(hex: string): string {
  const target = hexToRgb(hex);
  if (!target) return "";
  
  let closestCode = "9010";
  let minDistance = Infinity;

  for (const [code, val] of Object.entries(RAL_COLORS)) {
    const c = hexToRgb(val);
    if (!c) continue;
    const dist = colorDistance(target.r, target.g, target.b, c.r, c.g, c.b);
    if (dist < minDistance) {
      minDistance = dist;
      closestCode = code;
    }
  }
  return closestCode;
}

export function applyDarknessToHex(hex: string, darknessValue: number): string {
    const rgb = hexToRgb(hex);
    if (!rgb) return hex;
    // darknessValue ranges from 0 (black) to 1 (original color)
    const r = Math.round(rgb.r * darknessValue);
    const g = Math.round(rgb.g * darknessValue);
    const b = Math.round(rgb.b * darknessValue);
    return rgbToHex(r, g, b);
}
